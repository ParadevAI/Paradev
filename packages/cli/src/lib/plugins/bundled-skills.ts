import fs from "node:fs";
import path from "node:path";
import type { CheckIssue } from "./publish";

export const BUNDLED_PLUGIN_DIR = "plugins/superset";
const DOCS_SKILLS_PAGE = "apps/docs/content/docs/skills.mdx";
const GENERATED_TARGET =
	"packages/shared/src/plugins/bundled-skills.generated.ts";

export interface BundledSkill {
	name: string;
	description: string;
}

function shortDescription(file: string): string | null {
	if (!fs.existsSync(file)) return null;
	const parsed = Bun.YAML.parse(fs.readFileSync(file, "utf8")) as {
		interface?: { short_description?: unknown };
	} | null;
	const description = parsed?.interface?.short_description;
	return typeof description === "string" && description.trim()
		? description.trim()
		: null;
}

export function readBundledSkills(root: string): {
	skills: BundledSkill[];
	issues: CheckIssue[];
} {
	const dir = path.join(root, BUNDLED_PLUGIN_DIR, "skills");
	const skills: BundledSkill[] = [];
	const issues: CheckIssue[] = [];
	const names = fs
		.readdirSync(dir, { withFileTypes: true })
		.filter((entry) => entry.isDirectory())
		.map((entry) => entry.name)
		.filter((name) => fs.existsSync(path.join(dir, name, "SKILL.md")))
		.sort();
	for (const name of names) {
		const description = shortDescription(
			path.join(dir, name, "agents", "openai.yaml"),
		);
		if (!description) {
			issues.push({
				name: `skill ${name}`,
				problem: "agents/openai.yaml has no interface.short_description",
			});
			continue;
		}
		skills.push({ name, description });
	}
	return { skills, issues };
}

export function renderBundledSkills(skills: readonly BundledSkill[]): string {
	const entries = skills
		.map(
			(skill) =>
				`\t{\n\t\tname: ${JSON.stringify(skill.name)},\n\t\tdescription: ${JSON.stringify(skill.description)},\n\t},`,
		)
		.join("\n");
	return `// Generated by \`bun run generate:skills\` from ${BUNDLED_PLUGIN_DIR}/skills. Do not edit.

export const BUNDLED_SKILLS = [
${entries}
] as const;
`;
}

export function writeBundledSkills(root: string): CheckIssue[] {
	const { skills, issues } = readBundledSkills(root);
	if (issues.length) return issues;
	fs.writeFileSync(
		path.join(root, GENERATED_TARGET),
		renderBundledSkills(skills),
	);
	return [];
}

export function docsTableSkills(markdown: string): string[] {
	return [...markdown.matchAll(/^\|\s*`superset:([a-z0-9-]+)`\s*\|/gm)].map(
		(match) => match[1] as string,
	);
}

/** Skills named in the subject of each bullet under "How the skills work". */
export function readmeSkills(markdown: string): string[] {
	const section =
		markdown.split(/^## How the skills work$/m)[1]?.split(/^## /m)[0] ?? "";
	const bullets = section
		.split(/^- /m)
		.slice(1)
		.map((bullet) => bullet.replace(/\s+/g, " "));
	return bullets.flatMap((bullet) => {
		const boldEnd = bullet.lastIndexOf("**") + 2;
		const rest = bullet.slice(boldEnd);
		const subject =
			bullet.slice(0, boldEnd) +
			(rest.startsWith(" (") ? rest.slice(0, rest.indexOf(")") + 1) : "");
		return [...subject.matchAll(/`([a-z0-9-]+)`/g)].map(
			(match) => match[1] as string,
		);
	});
}

export function coverageIssues(
	label: string,
	named: readonly string[],
	bundled: readonly string[],
): CheckIssue[] {
	const issues: CheckIssue[] = [];
	const missing = bundled.filter((name) => !named.includes(name));
	const unknown = [...new Set(named.filter((name) => !bundled.includes(name)))];
	const repeated = [
		...new Set(named.filter((name, i) => named.indexOf(name) !== i)),
	];
	if (missing.length)
		issues.push({ name: label, problem: `missing ${missing.join(", ")}` });
	if (unknown.length)
		issues.push({
			name: label,
			problem: `names ${unknown.join(", ")}, which ${unknown.length === 1 ? "is not a bundled skill" : "are not bundled skills"}`,
		});
	if (repeated.length)
		issues.push({ name: label, problem: `repeats ${repeated.join(", ")}` });
	return issues;
}

export function bundledSkillsDrift(root: string): CheckIssue[] {
	const { skills, issues } = readBundledSkills(root);
	if (issues.length) return issues;

	const target = path.join(root, GENERATED_TARGET);
	const current = fs.existsSync(target)
		? fs.readFileSync(target, "utf8")
		: null;
	if (current !== renderBundledSkills(skills)) {
		issues.push({
			name: path.basename(target),
			problem: "bundled skill list is stale; run `bun run generate:skills`",
		});
	}

	const names = skills.map((skill) => skill.name);
	const read = (file: string) => fs.readFileSync(path.join(root, file), "utf8");
	issues.push(
		...coverageIssues(
			DOCS_SKILLS_PAGE,
			docsTableSkills(read(DOCS_SKILLS_PAGE)),
			names,
		),
		...coverageIssues(
			`${BUNDLED_PLUGIN_DIR}/README.md`,
			readmeSkills(read(`${BUNDLED_PLUGIN_DIR}/README.md`)),
			names,
		),
	);
	return issues;
}
